#!/usr/bin/env bash
# Every design state of qaHooks.sceneTable -> apps/too-much/build/shots/<name>.png (tools/shot.sh per shot).
# Start from a running app; the emulator floor is set first. ONLY="S06 S07" limits the list.
set -u
S="bash $(cd "$(dirname "$0")" && pwd)/shot.sh"
want() { [ -z "${ONLY:-}" ] || [[ " $ONLY " == *" $1 "* ]]; }
I="instant=true"
want S01 && $S S01 "room floor=0.4" "goto s=S01"
want S02 && $S S02 "goto s=S02"
want S03 && $S S03 "hold hold=false" "goto s=S03"
want S03b && $S S03b "goto s=S03b"
want S04 && $S S04-hands "reset_home" "input id=hands" "goto s=S04"
want S04 && $S S04-controller "input id=controller" "goto s=S04"
want S04b && $S S04b "input id=controller" "goto s=S04" "pin id=fridge x=1.8 y=1.5 z=-1.9" "hold hold=true"
want S04c && $S S04c "hold hold=false" "input id=controller" "goto s=S04c"
want S04c && $S S04c-nearer "ui id=adj_nearer"
want S04c && $S S04c-hands "input id=hands" "goto s=S04c"
want S05 && $S S05 "input id=auto" "goto s=S05"
want S06 && $S S06-L1 "seed n=1" "goto s=S06" "level n=1 $I"
want S06 && $S S06-L2 "level n=2 $I"
want S07 && $S S07-L3 "goto s=S07" "level n=3 $I"
want S08 && $S S08 "goto s=S08" "level n=4 $I hold=true"
want S09 && $S S09-from-task "hold hold=false" "goto s=S09"
want S09 && $S S09-from-baseline "goto s=S05" "quiet"
want S10 && $S S10 "goto s=S10"
want S10b && $S S10b-phone "goto s=S10" "card id=phone"
want S10b && $S S10b-lamp "card id=lamp"
want S10b && $S S10b-bag-front "card id=bag"
want S10b && $S S10b-far "goto s=S04" "pin id=lamp x=0 y=2.5 z=-4" "goto s=S10" "card id=lamp"
want S10b && $S S10b-done "card id=fridge" "unload id=fridge opt=0"
want S11 && $S S11 "goto s=S11"
want S12 && $S S12 "elapsed task=160 quiet=28" "goto s=S12"
want S13 && $S S13 "goto s=S06" "menu"
want S13 && $S S13-room "room_page on=true"
want S14 && $S S14 "menu" "goto s=S14"
want S15 && $S S15 "goto s=S15"
want S16 && $S S16-S03 "lang id=en" "goto s=S03"
want S16 && $S S16-S12 "goto s=S12"
want S16 && $S S16-zh-S10b "lang id=zh" "goto s=S10" "card id=lamp"
true
