/**
 * The files of design `audio.fileSpec` (generated by tools/gen_sounds.py into assets/audio): per
 * source a main layer and the cue layers, pulse sources as single shots.
 */
object SoundFiles {
    /** Loops per source: layer name -> asset file. */
    val loops: Map<SourceId, List<String>> =
        mapOf(
            SourceId.FRIDGE to listOf("fridge", "fridge_hiss"),
            SourceId.CLOCK to listOf("clock", "clock_hard"),
            SourceId.TAP to listOf("tap", "tap_bass"),
            SourceId.LAMP to listOf("lamp"),
        )

    val shots: Map<SourceId, List<String>> =
        mapOf(
            SourceId.BAG to (0 until 6).map { "bag_$it" },
            SourceId.PHONE to (0 until 2).map { "phone_$it" },
        )

    fun asset(name: String) = "audio/$name.wav"
}

/** Volume of each layer of a source for the current engine state, linear 0..1 (before the group). */
internal fun layerVolumes(engine: Engine, id: SourceId): List<Float> {
    val main = Engine.dbToLinear(engine.gainDb[id] ?: Engine.NEG_INF)
    return when (id) {
        SourceId.FRIDGE -> listOf(main, if (main > 0f) Engine.dbToLinear(engine.fridgeHissDb) else 0f)
        SourceId.CLOCK -> listOf(main * (1f - engine.clockHard), main * engine.clockHard)
        SourceId.TAP -> listOf(main * (1f - engine.tapBass), main * engine.tapBass)
        else -> listOf(main)
    }
}

/** A sound back-end. Everything on the main thread. */
interface SoundOut {
    val name: String

    /** Loads one more resource; false when all are loaded (called once per frame while building). */
    fun loadNext(): Boolean

    fun place(id: SourceId, position: io.embodit.toomuch.domain.model.Vec3)

    /** At <= 10 Hz: layer volumes and the group gain. [head]: for the stereo fallback. */
    fun apply(engine: Engine, head: io.embodit.toomuch.platform.tracking.HeadPose?)

    fun shot(id: SourceId, variant: Int, engine: Engine)

    /** Background: every source stops; foreground: loops run again (silent until the engine raises them). */
    fun setRunning(running: Boolean)

    fun release()
}

/**
 * The product path: one entity per source with an `ObjectAudioComponent` (HRTF + inverse-square
 * distance attenuation), one `AudioPlayerController` per layer, and every resource in one
 * `AudioMixerGroupResource` that carries intensity, mute and "Quiet now" (design `audio.engine`).
 */
class ObjectSoundOut(private val root: Entity) : SoundOut {
    override val name = "object"
    private val group = AudioMixerGroupResource(GROUP, 0f, 1f)
    private val holder = Entity()
    private val entities = HashMap<SourceId, Entity>()
    private val loops = HashMap<SourceId, MutableList<AudioPlayerController>>()
    private val shots = HashMap<SourceId, MutableList<AudioPlayerController>>()
    private val resources = ArrayList<AudioResource>()
    private val queue = ArrayList<Triple<SourceId, String, Boolean>>()
    private var running = true
    private var lastGroup = -1f

    init {
        runCatching { holder.setName("audioGroup") }
        root.addChild(holder)
        holder.components.set(AudioMixerGroupsComponent().apply { addMixerGroup(group) })
        for (id in SourceId.entries) {
            val e = Entity()
            runCatching { e.setName("audio:${id.tag}") }
            e.components.set(
                ObjectAudioComponent(
                    volume = 1f,
                    directivity = Directivity(0f, 1f),
                    distanceAttenuationMode = DistanceAttenuationMode.INVERSE_SQUARED,
                    reverbVolume = 0.3f,
                )
            )
            root.addChild(e)
            entities[id] = e
        }
        for ((id, names) in SoundFiles.loops) for (n in names) queue += Triple(id, n, true)
        for ((id, names) in SoundFiles.shots) for (n in names) queue += Triple(id, n, false)
    }

    override fun loadNext(): Boolean {
        if (queue.isEmpty()) return false
        val (id, n, loop) = queue.removeAt(0)
        val entity = entities[id] ?: return queue.isNotEmpty()
        runCatching {
            val res = AudioResource.load(n.replace("_", ""), "asset://${SoundFiles.asset(n)}", LoadType.FROM_ASSETS, AudioResourceConfig(mixerGroupID = GROUP))
            resources += res
            val c = entity.prepareAudio(res)
            c.setVolume(0f)
            if (loop) {
                c.setLoop(true)
                if (running) c.play()
                loops.getOrPut(id) { ArrayList() } += c
            } else {
                shots.getOrPut(id) { ArrayList() } += c
            }
            TmLog.i("AUDIO loaded $n loop=$loop")
        }.onFailure { TmLog.e("AUDIO load failed $n: $it", it) }
        return queue.isNotEmpty()
    }

    override fun place(id: SourceId, position: io.embodit.toomuch.domain.model.Vec3) {
        val e = entities[id] ?: return
        runCatching { e.components[com.pico.spatial.core.ecs.TransformComponent::class.java]?.setPosition(com.pico.spatial.core.math.Vector3(position.x, position.y, position.z)) }
    }

    override fun apply(engine: Engine, head: io.embodit.toomuch.platform.tracking.HeadPose?) {
        if (engine.group != lastGroup) {
            lastGroup = engine.group
            runCatching { group.setVolume(engine.group.coerceIn(0f, 1f)) }
        }
        for ((id, list) in loops) {
            val v = layerVolumes(engine, id)
            list.forEachIndexed { i, c -> runCatching { c.setVolume(v.getOrElse(i) { 0f }) } }
        }
    }

    override fun shot(id: SourceId, variant: Int, engine: Engine) {
        val list = shots[id] ?: return
        if (list.isEmpty() || !running) return
        val c = list[variant.coerceIn(0, list.size - 1)]
        val v = Engine.dbToLinear(engine.gainDb[id] ?: Engine.NEG_INF)
        runCatching {
            c.setVolume(v)
            c.stop()
            c.seekTo(0L)
            c.play()
        }.onFailure { TmLog.w("AUDIO shot failed ${id.tag}: $it") }
    }

    override fun setRunning(running: Boolean) {
        if (this.running == running) return
        this.running = running
        for (list in loops.values) for (c in list) runCatching { if (running) c.play() else c.pause() }
        if (!running) for (list in shots.values) for (c in list) runCatching { c.stop() }
    }

    override fun release() {
        for (list in loops.values + shots.values) for (c in list) runCatching {
            c.stop()
            c.close()
        }
        loops.clear()
        shots.clear()
        runCatching { holder.components[AudioMixerGroupsComponent::class.java]?.clear() }
        runCatching { group.close() }
        resources.forEach { runCatching { it.close() } }
        resources.clear()
        for (e in entities.values) runCatching { e.destroy(true) }
        runCatching { holder.destroy(true) }
        entities.clear()
    }

    companion object {
        const val GROUP = "TooMuchMix"
    }
}

/**
 * QA fallback only (debug `audio soundpool`, design `audio.fallbackForEmulator`): SoundPool with a
 * left / right pan from the head-relative azimuth, so the emulator can be heard at all.
 */
class PoolSoundOut(context: Context) : SoundOut {
    override val name = "soundpool"
    private val pool =
        SoundPool.Builder().setMaxStreams(16).setAudioAttributes(AudioAttributes.Builder().setUsage(AudioAttributes.USAGE_GAME).setContentType(AudioAttributes.CONTENT_TYPE_SONIFICATION).build()).build()
    private val app = context.applicationContext
    private val loopIds = HashMap<String, Int>()
    private val shotIds = HashMap<String, Int>()
    private val streams = HashMap<String, Int>()
    private val ready = HashSet<Int>()
    private val positions = HashMap<SourceId, io.embodit.toomuch.domain.model.Vec3>()
    private val queue = ArrayList<Pair<String, Boolean>>()
    private var running = true
    private var engineRef: Engine? = null

    init {
        pool.setOnLoadCompleteListener { _, sampleId, status -> if (status == 0) ready += sampleId }
        for (names in SoundFiles.loops.values) for (n in names) queue += n to true
        for (names in SoundFiles.shots.values) for (n in names) queue += n to false
    }

    override fun loadNext(): Boolean {
        if (queue.isEmpty()) return false
        val (n, loop) = queue.removeAt(0)
        runCatching {
            val id = app.assets.openFd(SoundFiles.asset(n)).use { pool.load(it, 1) }
            if (loop) loopIds[n] = id else shotIds[n] = id
        }.onFailure { TmLog.e("AUDIO pool load failed $n: $it", it) }
        return queue.isNotEmpty()
    }

    override fun place(id: SourceId, position: io.embodit.toomuch.domain.model.Vec3) {
        positions[id] = position
    }

    private fun pan(id: SourceId, head: io.embodit.toomuch.platform.tracking.HeadPose?): Pair<Float, Float> {
        val p = positions[id] ?: return 0.7f to 0.7f
        val h = head ?: return 0.7f to 0.7f
        val to = (p - h.position).normalized()
        val x = to.dot(h.right).coerceIn(-1f, 1f)
        return (0.5f * (1f - x)).coerceIn(0.1f, 1f) to (0.5f * (1f + x)).coerceIn(0.1f, 1f)
    }

    override fun apply(engine: Engine, head: io.embodit.toomuch.platform.tracking.HeadPose?) {
        engineRef = engine
        for ((id, names) in SoundFiles.loops) {
            val v = layerVolumes(engine, id)
            val (l, r) = pan(id, head)
            names.forEachIndexed { i, n ->
                val sample = loopIds[n] ?: return@forEachIndexed
                if (sample !in ready) return@forEachIndexed
                val g = v.getOrElse(i) { 0f } * engine.group
                var stream = streams[n]
                if (stream == null && running) {
                    stream = pool.play(sample, 0f, 0f, 1, -1, 1f)
                    streams[n] = stream
                }
                if (stream != null) pool.setVolume(stream, g * l, g * r)
            }
        }
    }

    override fun shot(id: SourceId, variant: Int, engine: Engine) {
        if (!running) return
        val names = SoundFiles.shots[id] ?: return
        val sample = shotIds[names[variant.coerceIn(0, names.size - 1)]] ?: return
        val g = Engine.dbToLinear(engine.gainDb[id] ?: Engine.NEG_INF) * engine.group
        pool.play(sample, g * 0.7f, g * 0.7f, 2, 0, 1f)
    }

    override fun setRunning(running: Boolean) {
        if (this.running == running) return
        this.running = running
        if (running) pool.autoResume() else pool.autoPause()
    }

    override fun release() {
        runCatching { pool.release() }
        streams.clear()
    }
}

/** UI clicks (design `uiSfx`): snap "tick" at -18 dB, unload "ding" at -16 dB; not spatialised. */
class UiSfx(context: Context) {
    private val pool = SoundPool.Builder().setMaxStreams(2).setAudioAttributes(AudioAttributes.Builder().setUsage(AudioAttributes.USAGE_ASSISTANCE_SONIFICATION).setContentType(AudioAttributes.CONTENT_TYPE_SONIFICATION).build()).build()
    private val snap = runCatching { context.assets.openFd(SoundFiles.asset("ui_snap")).use { pool.load(it, 1) } }.getOrNull()
    private val ding = runCatching { context.assets.openFd(SoundFiles.asset("ui_ding")).use { pool.load(it, 1) } }.getOrNull()

    /** [muted] follows the panel's mute switch and "Quiet now". */
    fun snap(muted: Boolean) {
        if (!muted) snap?.let { pool.play(it, SNAP_GAIN, SNAP_GAIN, 1, 0, 1f) }
    }

    fun ding(muted: Boolean) {
        if (!muted) ding?.let { pool.play(it, DING_GAIN, DING_GAIN, 1, 0, 1f) }
    }

    fun release() = runCatching { pool.release() }

    private companion object {
        const val SNAP_GAIN = 0.126f
        const val DING_GAIN = 0.158f
    }
}
